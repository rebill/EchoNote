"""Vendor the libopus sources that crates/echonote-opus compiles.

Downloads the pinned release tarball from Xiph, checks its SHA-256, and copies only the
plain-C floating-point codec: the source lists come from upstream's *_sources.mk, plus every
header next to them. DNN (deep PLC, DRED, OSCE), SIMD intrinsics, demos and tests are left
out. Only the Python standard library is used.

Usage: python3 scripts/dev/vendor_opus.py [--archive opus-1.6.1.tar.gz]
"""

from __future__ import annotations

import argparse
import hashlib
import io
import posixpath
import shutil
import sys
import tarfile
import urllib.request
from pathlib import Path

VERSION = "1.6.1"
URL = f"https://downloads.xiph.org/releases/opus/opus-{VERSION}.tar.gz"
SHA256 = "6ffcb593207be92584df15b32466ed64bbec99109f007c82205f0194572411a1"

REPO_ROOT = Path(__file__).resolve().parents[2]
DEST = REPO_ROOT / "crates" / "echonote-opus" / "opus"

# (makefile fragment, variables) whose .c files are compiled.
SOURCE_LISTS = [
    ("celt_sources.mk", ["CELT_SOURCES"]),
    ("silk_sources.mk", ["SILK_SOURCES", "SILK_SOURCES_FLOAT"]),
    ("opus_sources.mk", ["OPUS_SOURCES", "OPUS_SOURCES_FLOAT"]),
]
# Compiles to an empty object unless SILK_DEBUG is set (ranlib warns about it).
SKIPPED_SOURCES = {"silk/debug.c"}
HEADER_DIRS = ["include", "celt", "silk", "silk/float", "src"]
LICENSE_FILES = ["COPYING", "AUTHORS", "package_version"]


def make_variables(text: str) -> dict[str, list[str]]:
    """Parse `NAME = a \\ b` assignments from an automake fragment."""
    variables: dict[str, list[str]] = {}
    for statement in text.replace("\\\n", " ").splitlines():
        name, sep, value = statement.partition("=")
        if sep and name.strip().isidentifier():
            variables[name.strip()] = value.split()
    return variables


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--archive", type=Path, help="use a local copy of the release tarball")
    args = parser.parse_args()

    if args.archive:
        data = args.archive.read_bytes()
    else:
        with urllib.request.urlopen(URL, timeout=120) as response:
            data = response.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        print(f"sha256 mismatch: got {digest}, want {SHA256}", file=sys.stderr)
        return 1

    with tarfile.open(fileobj=io.BytesIO(data)) as tar:
        prefix = f"opus-{VERSION}/"
        members = {m.name.removeprefix(prefix): m for m in tar.getmembers() if m.isfile()}

        def read(name: str) -> bytes:
            return tar.extractfile(members[name]).read()

        sources: list[str] = []
        for fragment, names in SOURCE_LISTS:
            variables = make_variables(read(fragment).decode())
            for name in names:
                sources.extend(s for s in variables[name] if s not in SKIPPED_SOURCES)
        headers = [
            name
            for name in members
            if name.endswith(".h") and posixpath.dirname(name) in HEADER_DIRS
        ]

        if DEST.exists():
            shutil.rmtree(DEST)
        for name in sorted(set(sources + headers + LICENSE_FILES)):
            target = DEST / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(read(name))

    (DEST / "sources.txt").write_text("".join(f"{name}\n" for name in sources))
    (DEST / "VENDOR.txt").write_text(
        f"libopus {VERSION}\n{URL}\nsha256 {SHA256}\n"
        "Generated by scripts/dev/vendor_opus.py; do not edit by hand.\n"
    )
    print(f"vendored {len(sources)} sources and {len(headers)} headers into {DEST}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
